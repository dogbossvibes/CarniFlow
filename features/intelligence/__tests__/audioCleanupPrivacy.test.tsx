import TestRenderer, { act, type ReactTestRenderer } from 'react-test-renderer';
import { AppState } from 'react-native';
import { IntelligenceConversation } from '../IntelligenceConversation';
import { IntelligenceSession } from '../session';
import { IntelligenceConsentController } from '../consentController';
import { ServerSpeechCapture } from '../serverSpeechCapture';
import { conversationCopy as copy } from '../copy';
let renderer: ReactTestRenderer;
beforeEach(() => jest.spyOn(AppState, 'addEventListener').mockReturnValue({ remove: jest.fn() }));
afterEach(() => { if (renderer) act(() => renderer.unmount()); jest.restoreAllMocks(); });
it.each(['revoke', 'policy removal'] as const)('keeps owned local deletion accessible after %s without renewed consent or network processing', async action => {
  const session = new IntelligenceSession({ respond: jest.fn() }, () => 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa');
  session.selectScope({ ownerId: 'owner', dogId: 'dog' });
  session.configure({ id: 'p', enabled: true, providerLabel: 'P', disclosure: 'D', retentionSummary: 'R', monthlyBudgetChfCents: 500 });
  const intent = session.beginConsent(true, true, 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa', 0)!;
  session.confirmConsent(intent, { version: 1, accountId: 'owner', policyId: 'p', text: true, audio: true, revision: 1, grantedAt: '2026-10-23T06:00:00Z' });
  const gateway = { readRevision: jest.fn(), grant: jest.fn(), revoke: jest.fn(async () => ({ version: 1, accountId: 'owner', policyId: 'p', revoked: true, revision: 2, revokedAt: '2026-10-23T06:00:00Z' })) };
  const consent = new IntelligenceConsentController(session, { read: async () => [], write: async () => {} }, gateway, () => 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa');
  const take = { start: jest.fn(), bytes: jest.fn(), close: jest.fn(async () => false) };
  const port = { available: () => true, permitted: jest.fn(async () => true), recover: jest.fn(async () => true), prepare: jest.fn(async () => take) };
  const transcription = { transcribe: jest.fn() };
  const capture = new ServerSpeechCapture(session, port, transcription, () => 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa', () => true, () => true);
  const buttons = (label: string) => renderer.root.findAll(n => n.props.accessibilityLabel === label && typeof n.props.onPress === 'function');
  await act(async () => { renderer = TestRenderer.create(<IntelligenceConversation session={session} consent={consent} speech={capture} identity={{ accountId: 'owner', dogId: 'dog', dogName: 'Malu' }} onBack={() => {}} />); });
  await act(async () => { await capture.start(); });
  await act(async () => { if (action === 'revoke') buttons(copy.revoke)[0].props.onPress(); else session.configure(null); });
  expect(session.snapshot().consent).toBeNull(); expect(capture.getStatus()).toBe('cleanupPending');
  expect(buttons(copy.retryAudioCleanup)).toHaveLength(1);
  const copyVisible = renderer.root.findAll(n => n.props.children === copy.cleanupPending); expect(copyVisible.length).toBeGreaterThan(0);
  expect(gateway.grant).not.toHaveBeenCalled(); expect(transcription.transcribe).not.toHaveBeenCalled();
  take.close.mockResolvedValue(true);
  await act(async () => { buttons(copy.retryAudioCleanup)[0].props.onPress(); });
  expect(capture.getStatus()).toBe('idle'); expect(buttons(copy.retryAudioCleanup)).toHaveLength(0);
  expect(session.snapshot().consent).toBeNull(); expect(port.permitted).toHaveBeenCalledTimes(1); expect(take.start).toHaveBeenCalledTimes(1);
  expect(gateway.grant).not.toHaveBeenCalled(); expect(transcription.transcribe).not.toHaveBeenCalled();
  capture.dispose();
});
